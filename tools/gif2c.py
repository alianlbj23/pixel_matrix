"""Convert an animated GIF into a C++ source file of RGB888 frames for the panel.

Called by menu.sh ("Convert GIF"); the output main/gif_anim_data.cpp is compiled
into the firmware. Each frame is scaled to fit width x height (keeping aspect
ratio), centered, with transparent / empty areas left black.
"""
import argparse
import logging
import pathlib
import sys

from PIL import Image, ImageSequence, UnidentifiedImageError

log = logging.getLogger("gif2c")

MAX_INPUT_BYTES = 10 * 1024 * 1024
MAX_FRAMES = 64
MAX_SIDE = 256
DEFAULT_DURATION_MS = 100
MIN_DURATION_MS = 20
MAX_DURATION_MS = 10000


class GifError(Exception):
    """Input GIF or conversion parameters are invalid."""


def clamp_duration(value):
    if not isinstance(value, (int, float)) or value <= 0:
        return DEFAULT_DURATION_MS
    return int(min(max(value, MIN_DURATION_MS), MAX_DURATION_MS))


def _fit_frame(frame, width, height):
    rgba = frame.convert("RGBA")
    scale = min(width / rgba.width, height / rgba.height)
    new_w = max(1, round(rgba.width * scale))
    new_h = max(1, round(rgba.height * scale))
    scaled = rgba.resize((new_w, new_h), Image.LANCZOS)
    canvas = Image.new("RGB", (width, height), (0, 0, 0))
    canvas.paste(scaled, ((width - new_w) // 2, (height - new_h) // 2), scaled)
    return canvas.tobytes()


def load_frames(path, width, height):
    """Returns [(rgb888_bytes, duration_ms), ...]; raises GifError on bad input."""
    path = pathlib.Path(path)
    if not (isinstance(width, int) and isinstance(height, int)
            and 0 < width <= MAX_SIDE and 0 < height <= MAX_SIDE):
        raise GifError(f"target size must be 1..{MAX_SIDE}, got {width}x{height}")
    if not path.is_file():
        raise GifError(f"file not found: {path}")
    size = path.stat().st_size
    if size > MAX_INPUT_BYTES:
        raise GifError(f"file too large: {size} bytes (max {MAX_INPUT_BYTES})")

    try:
        with Image.open(path) as im:
            if im.format != "GIF":
                raise GifError(f"not a GIF file (format={im.format}): {path}")
            n_frames = getattr(im, "n_frames", 1)
            if n_frames > MAX_FRAMES:
                raise GifError(f"too many frames: {n_frames} (max {MAX_FRAMES})")
            frames = []
            for frame in ImageSequence.Iterator(im):
                duration = clamp_duration(frame.info.get("duration"))
                frames.append((_fit_frame(frame, width, height), duration))
    except (UnidentifiedImageError, OSError) as exc:
        raise GifError(f"cannot read GIF {path}: {exc}") from exc

    if not frames:
        raise GifError(f"GIF has no frames: {path}")
    return frames


def render_cpp(frames, width, height, source_name):
    lines = [
        f"// GENERATED by tools/gif2c.py from {source_name}. Do not edit by hand;",
        "// re-run menu.sh \"Convert GIF\" instead.",
        '#include "gif_anim.h"',
        "",
        "namespace gif_anim {",
        "",
        f"const uint16_t kWidth = {width};",
        f"const uint16_t kHeight = {height};",
        "",
    ]
    for i, (rgb, _) in enumerate(frames):
        lines.append(f"static const uint8_t kFrame{i}[{len(rgb)}] = {{")
        for off in range(0, len(rgb), 24):
            chunk = ", ".join(f"0x{b:02x}" for b in rgb[off:off + 24])
            lines.append(f"    {chunk},")
        lines.append("};")
        lines.append("")
    lines.append("const Frame kFrames[] = {")
    for i, (_, duration) in enumerate(frames):
        lines.append(f"    {{kFrame{i}, {duration}}},")
    lines.append("};")
    lines.append(f"const size_t kFrameCount = {len(frames)};")
    lines.append("")
    lines.append("}  // namespace gif_anim")
    lines.append("")
    return "\n".join(lines)


def main(argv=None):
    logging.basicConfig(level=logging.INFO, format="%(name)s: %(message)s")
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("input", help="source .gif")
    parser.add_argument("output", help="generated .cpp path")
    parser.add_argument("--width", type=int, default=64)
    parser.add_argument("--height", type=int, default=32)
    args = parser.parse_args(argv)

    try:
        frames = load_frames(args.input, args.width, args.height)
    except GifError as exc:
        log.error("%s", exc)
        return 1

    out = pathlib.Path(args.output)
    try:
        out.write_text(render_cpp(frames, args.width, args.height, pathlib.Path(args.input).name))
    except OSError as exc:
        log.error("cannot write %s: %s", out, exc)
        return 1
    total = sum(d for _, d in frames)
    log.info("wrote %s: %d frame(s), %dx%d, loop %d ms", out, len(frames),
             args.width, args.height, total)
    return 0


if __name__ == "__main__":
    sys.exit(main())
